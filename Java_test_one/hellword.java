public class hellword{
    public static void main(String[] args){
        System.out.println("hello world!");
        System.out.println("我正在学习Java, 目标是成为软件开发工程师");
    }
}
/*
public：访问修饰符，表示这个类/方法是公开的。
class：关键字，用来声明一个类。
static：静态修饰符，表示这个方法属于类本身，不需要实例化对象就能调用。
void：表示这个方法没有返回值。
String[] args：命令行参数，目前了解即可，后续会讲。
System.out.println()：Java内置的打印方法，打印完会自动换行。
*/
